#!/usr/bin/env python3
"""Run the ETCS moving block model over a set of configurations.

For every configuration it writes a parameters.pl, runs the three queries and
collects verdict, wall-clock time, peak memory and the search counters.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import time

BASE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "etcs-l3")

PARAMS_TEMPLATE = """% General parameters (generated by driver.py -- configuration: {name})
delta_speed({delta_speed}).
track_start({track_start}).
track_end({track_end}).
ispeed({ispeed}).
max_speed({max_speed}).
min_speed({min_speed}).
ilength({ilength}).
time_start(0).
safe_margin({safe_margin}).
tpr_interval({tpr_interval}).
safety_speed({safety_speed}).
march_interval({march_interval}).
reservation_speed_factor({factor}).
max_time({max_time}).

{positions}

tpr_tick(Time) :-
\ttpr_interval(TPR),
\tTime mod TPR =:= 0.
"""

DEFAULTS = dict(
    name="reference",
    delta_speed=0.25, track_start=0, track_end=20,
    ispeed=0.5, min_speed=0.5, max_speed=0.75,
    ilength=1, safe_margin=5, tpr_interval=4, safety_speed=0.0001,
    march_interval=2, factor=1.2, max_time=200,
    positions={"t1": 5, "t2": 12, "t3": 19, "t4": 70},
)


def write_model(workdir, cfg, mutate=None):
    if os.path.exists(workdir):
        shutil.rmtree(workdir)
    shutil.copytree(BASE, workdir)
    pos = "\n".join("iposition({}, {}).".format(k, v)
                    for k, v in cfg["positions"].items())
    fields = {k: v for k, v in cfg.items() if k != "positions"}
    params = PARAMS_TEMPLATE.format(positions=pos, **fields)
    with open(os.path.join(workdir, "parameters.pl"), "w") as fh:
        fh.write(params)
    if mutate:
        mutate(workdir)


def run_query(workdir, goal, timeout):
    cmd = ["/usr/bin/time", "-f", "MAXRSS=%M",
           "gprolog", "--consult-file", "system.pl", "--query-goal", goal]
    start = time.time()
    try:
        proc = subprocess.run(cmd, cwd=workdir, stdin=subprocess.DEVNULL,
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                              timeout=timeout)
        out = proc.stdout.decode("utf-8", "replace")
    except subprocess.TimeoutExpired as exc:
        out = (exc.stdout or b"").decode("utf-8", "replace")
        return {"verdict": "timeout", "time": timeout, "out": out}
    elapsed = time.time() - start
    res = {"time": round(elapsed, 3), "out": out}
    m = re.search(r"MAXRSS=(\d+)", out)
    if m:
        res["maxrss_kb"] = int(m.group(1))
    m = re.search(r"states=(\d+);runs=(\d+);cuts=(\d+);horizon=(\d+);", out)
    if m:
        (res["states"], res["runs"],
         res["cuts"], res["horizon"]) = (int(m.group(i)) for i in (1, 2, 3, 4))
    # the goal itself is echoed by the top level, so only a bare line counts
    lines = [l.strip() for l in out.splitlines()]
    if "VERDICT:found" in lines:
        res["verdict"] = "found"
    elif "VERDICT:unsat" in lines:
        res["verdict"] = "unsat"
    else:
        res["verdict"] = "error"
    m = re.search(r"^rows=(\d+)$", out, re.M)
    if m:
        res["rows"] = int(m.group(1))
    res.pop("out", None)
    return res


def goal_for(query, trains):
    lst = "[" + ",".join(trains) + "]"
    return ("reset_counters, "
            "( {q}({t}, L) -> write('VERDICT:found'), nl, length(L, N), "
            "format(\"rows=~w~n\", [N]) ; write('VERDICT:unsat'), nl ), "
            "report_counters, halt").format(q=query, t=lst)


def evaluate(cfg, trains=("t1", "t2"), timeout=300, mutate=None, tag="run", reps=1):
    """Run the three queries. With reps > 1 the reported time is the median of
    the repetitions; verdict and counters must agree across them."""
    workdir = os.path.join(os.path.dirname(BASE), "work_" + tag)
    write_model(workdir, cfg, mutate)
    out = {"config": cfg["name"], "trains": list(trains), "reps": reps}
    for query in ("safe_run", "reach_hazard", "reach_accident"):
        runs = [run_query(workdir, goal_for(query, trains), timeout)
                for _ in range(reps)]
        res = dict(runs[0])
        times = sorted(r["time"] for r in runs)
        res["time"] = times[len(times) // 2]
        res["time_min"], res["time_max"] = times[0], times[-1]
        verdicts = {r["verdict"] for r in runs}
        states = {r.get("states") for r in runs}
        if len(verdicts) > 1 or len(states) > 1:
            res["unstable"] = {"verdicts": sorted(verdicts),
                               "states": sorted(x for x in states if x is not None)}
        out[query] = res
    return out


if __name__ == "__main__":
    cfg = dict(DEFAULTS)
    if len(sys.argv) > 1:
        cfg.update(json.loads(sys.argv[1]))
    print(json.dumps(evaluate(cfg), indent=1))
